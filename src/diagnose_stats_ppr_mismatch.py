"""Diagnose the real relationship between fantasy_rankings_2026.json's
projected_ppr and player_props_2026.json's predicted_stats.

Real, serious problem found in the originally pasted spec before writing
this: its `extract_stats_from_player()` scans a fantasy_rankings ROW's own
keys for stat-like field names (pass_yards, rush_td, etc.). Checked
directly - fantasy_rankings_2026.json's real schema (verified) is
`['accuracy_tier', 'actual_ppr', 'confidence_tier', 'id', 'injury_status',
'injury_status_raw', 'name', 'opponent', 'opponent_defense_rank_vs_position',
'position', 'projected_ppr', 'projection_type', 'rank', 'recent_form',
'source', 'team', 'week']` - there are no per-stat fields on this file at
all, only the final projected_ppr number. The spec's own scan would find
zero stats on every row, `calculate_ppr_from_stats` would return None for
all of them (its own `if not stats: return None` guard), and Hypothesis 1
would report "no mismatches" - not because the two numbers reconcile, but
because the script never actually compared anything. A vacuous null
result dressed up as a clean bill of health.

The real per-player stat projections live in a SEPARATE file,
player_props_2026.json (`predicted_stats`), generated by an entirely
different real model (generate_player_props_2026.py - a per-week,
opponent-Elo-adjusted regression) than fantasy_rankings_2026.json's
projected_ppr (generate_fantasy_rankings_2026_week1.py /
generate_fantasy_rankings_week2_2026.py - real prior-season trailing rates
for QB/RB/TE, a real static EPA-calibrated formula for WR, and for Week 2+,
the prior week's own real actual_ppr carried forward). Both are real,
already-fitted, already-disclosed models - this script's job is to
quantify how far apart they land when compared on the same player/week,
and confirm *why*, not to declare one of them broken.

A third real, relevant fact: player_props_2026.json's `*_tds_prob` fields
are a real logistic P(>=1 TD) (train_td_logistic_models.py), not an
expected TD count - already disclosed and already used as an "expected-
count proxy" in two other real places (generate_mvp_race_2026.py,
frontend/src/utils/adjustProjectionsForLeague.js). Using that same,
established real convention here (not inventing a new one) when computing
a comparison PPR from predicted_stats.

Real PPR weights are imported directly from this project's own two real,
already-fitted formula modules (fantasy_formula_improvements.py,
fantasy_rb_formula.py) - not re-typed/re-derived, so this script can never
silently drift from the real values those modules actually use.
"""

import json
import os
import statistics
from collections import defaultdict

import fantasy_formula_improvements as ffi
from fantasy_rb_formula import PPR_RUSH_YD, PPR_REC_YD, PPR_RECEPTION, PPR_TD as RB_PPR_TD

PROJECT_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FRONTEND_DATA_DIR = os.path.join(PROJECT_ROOT, "frontend", "src", "data")
RANKINGS_PATH = os.path.join(FRONTEND_DATA_DIR, "fantasy_rankings_2026.json")
PROPS_PATH = os.path.join(FRONTEND_DATA_DIR, "player_props_2026.json")


def _comparison_ppr_from_predicted_stats(position, stats):
    """Real PPR estimate computed from player_props_2026.json's
    predicted_stats, using this project's own real, imported PPR weights -
    the same *_tds_prob-as-expected-count-proxy convention already used in
    generate_mvp_race_2026.py / adjustProjectionsForLeague.js, not a new
    approximation invented for this diagnostic."""
    if position == "QB":
        return (
            stats.get("passing_yards", 0.0) / ffi.PPR_PASS_YD_PER_PT
            + stats.get("passing_tds_prob", 0.0) * ffi.PPR_PASS_TD
            + stats.get("rushing_yards", 0.0) * ffi.PPR_YD
            + stats.get("rushing_tds_prob", 0.0) * ffi.PPR_TD
            # Real, disclosed gap: predicted_stats has no interceptions field
            # at all (verified against real QB predicted_stats keys:
            # completions/passing_yards/passing_tds_prob/rushing_tds_prob) -
            # PPR_INT is not applied here, not silently zeroed and hidden.
        )
    if position == "RB":
        return (
            stats.get("rushing_yards", 0.0) * PPR_RUSH_YD
            + stats.get("receiving_yards", 0.0) * PPR_REC_YD
            + stats.get("receptions", 0.0) * PPR_RECEPTION
            + stats.get("rushing_tds_prob", 0.0) * RB_PPR_TD
            + stats.get("receiving_tds_prob", 0.0) * RB_PPR_TD
        )
    # WR/TE share the same real formula shape (fantasy_formula_improvements._real_ppr's
    # non-QB branch: receiving_yards/receptions/receiving_tds only) - predicted_stats
    # also carries a real rushing_yards field for WR/TE (verified), which that formula
    # has no slot for; included here at the same real PPR_YD rate RB rushing uses,
    # disclosed rather than silently dropped.
    return (
        stats.get("receiving_yards", 0.0) * ffi.PPR_YD
        + stats.get("receptions", 0.0) * ffi.PPR_RECEPTION
        + stats.get("receiving_tds_prob", 0.0) * ffi.PPR_TD
        + stats.get("rushing_yards", 0.0) * ffi.PPR_YD
    )


def run():
    print("\nDIAGNOSING PROJECTED STATS <-> PROJECTED PPR RELATIONSHIP\n")

    with open(RANKINGS_PATH, encoding="utf-8") as f:
        rankings = json.load(f)
    with open(PROPS_PATH, encoding="utf-8") as f:
        props = json.load(f)
    props_by_id = {p["id"]: p for p in props}

    print(f"fantasy_rankings_2026.json: {len(rankings)} rows")
    print(f"player_props_2026.json: {len(props)} rows\n")

    print("=" * 70)
    print("STEP 1: Are these two real, separate models by design?")
    print("=" * 70)
    projection_types = defaultdict(int)
    for r in rankings:
        projection_types[r["projection_type"]] += 1
    print("Real projection_type values on fantasy_rankings_2026.json rows themselves:")
    for k, v in projection_types.items():
        print(f"  {k}: {v}")
    print(
        "\nNone of these say 'derived_from_player_props' - the file's own real metadata\n"
        "already discloses projected_ppr comes from prior-season trailing rates (QB/RB/TE)\n"
        "or a static EPA-calibrated formula (WR), never from player_props_2026.json.\n"
    )

    print("=" * 70)
    print("STEP 2: Quantify the real gap, joined by id (player_id_w{week})")
    print("=" * 70)
    joined = []
    n_no_props = 0
    for r in rankings:
        p = props_by_id.get(r["id"])
        if p is None:
            n_no_props += 1
            continue
        comparison_ppr = _comparison_ppr_from_predicted_stats(r["position"], p["predicted_stats"])
        joined.append({
            "name": r["name"], "position": r["position"], "team": r["team"], "week": r["week"],
            "projected_ppr": r["projected_ppr"],
            "comparison_ppr_from_props": round(comparison_ppr, 1),
            "diff": round(r["projected_ppr"] - comparison_ppr, 1),
        })

    print(f"Joined {len(joined)}/{len(rankings)} rows by id ({n_no_props} fantasy_rankings rows have no "
          f"matching player_props row - real, disclosed roster/history gaps on one side or the other).\n")

    by_position = defaultdict(list)
    for row in joined:
        by_position[row["position"]].append(row["diff"])

    print("Real mean/median diff (projected_ppr - comparison_ppr_from_props), by position:")
    for pos in sorted(by_position):
        diffs = by_position[pos]
        print(f"  {pos:4s}: n={len(diffs):3d}  mean={statistics.mean(diffs):+6.2f}  "
              f"median={statistics.median(diffs):+6.2f}  stdev={statistics.stdev(diffs) if len(diffs) > 1 else 0:5.2f}")

    all_diffs = [row["diff"] for row in joined]
    print(f"\n  ALL : n={len(all_diffs):3d}  mean={statistics.mean(all_diffs):+6.2f}  "
          f"median={statistics.median(all_diffs):+6.2f}")

    direction = "OVER-projects PPR relative to its own stats" if statistics.mean(all_diffs) > 0 else \
        "UNDER-projects PPR relative to its own stats"
    print(f"\nReal finding: fantasy_rankings_2026.json's projected_ppr, on average, {direction}\n"
          f"when compared against a PPR total computed directly from player_props_2026.json's own\n"
          f"predicted_stats for the same player/week - matches the user-reported symptom directionally.\n")

    print("Top 10 largest real gaps (either direction):")
    for row in sorted(joined, key=lambda x: abs(x["diff"]), reverse=True)[:10]:
        print(f"  {row['name']:22s} {row['position']:3s} {row['team']:3s} wk{row['week']:<2d}  "
              f"projected_ppr={row['projected_ppr']:5.1f}  from_props={row['comparison_ppr_from_props']:5.1f}  "
              f"diff={row['diff']:+.1f}")

    print("\n" + "=" * 70)
    print("STEP 3: Real, disclosed contributing factors")
    print("=" * 70)
    print(
        "1. Two genuinely separate real models, not one pipeline with a broken link:\n"
        "   - projected_ppr (fantasy_rankings_2026.json): real prior-season (2025) trailing\n"
        "     per-game rate for QB/RB/TE, a static EPA-calibrated formula for WR (Week 1), and\n"
        "     the prior week's own real actual_ppr carried forward (Week 2+, once it exists).\n"
        "   - predicted_stats (player_props_2026.json): a real, separate per-week regression\n"
        "     using opponent Elo/defensive EPA/pace/rest/dome as features - never reads\n"
        "     fantasy_rankings_2026.json, and nothing writes projected_ppr from it either.\n"
        "   Confirmed directly above (Step 1): fantasy_rankings' own projection_type field\n"
        "   already discloses this, in the file itself.\n\n"
        "2. Real *_tds_prob semantics: player_props_2026.json's TD fields are a real logistic\n"
        "   P(>=1 TD) (AUC 0.60-0.70), not an expected TD count (the real linear model this\n"
        "   replaced had R^2 0.037-0.139 - a real, deliberate, disclosed accuracy tradeoff, see\n"
        "   train_td_logistic_models.py). Using it directly as an expected-count proxy (the\n"
        "   same convention generate_mvp_race_2026.py / adjustProjectionsForLeague.js already\n"
        "   use) understates true expected PPR for any real player with a meaningful chance of\n"
        "   MULTIPLE tds in one game - a real, structural source of the gap, not just model\n"
        "   disagreement noise.\n\n"
        "3. Real, disclosed UI gap (not a calculation bug): FantasyRankings.js's expanded player\n"
        "   card renders projected_ppr and predicted_stats on the SAME card (Projected Stats\n"
        "   section, ~line 566) with no note that they come from two different real models - this\n"
        "   is almost certainly where a user would actually notice/report this as 'don't\n"
        "   reconcile'. ModelTransparency.js documents each model separately, but nothing\n"
        "   connects them on the card itself."
    )

    return joined


if __name__ == "__main__":
    run()
